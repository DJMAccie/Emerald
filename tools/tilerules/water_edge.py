#!/usr/bin/env python3
"""Tegelregel 2: watertegels met oever (zand/schuim) erin gebakken -> de gewone open-watertegel met hetzelfde gedrag
in hetzelfde General-paar. Gen3Boundary herhaalt water voorbij de kaartrand; een oevertegel herhalen herhaalde de oever.

Een watertegel (gedrag vijver/diep/zee, echt gebruikt op een kaart) is 'puur' als >= 97% van de pixels blauw is,
'oever' bij 50-97%. Elke oevertegel krijgt de meest gebruikte pure tegel met hetzelfde gedrag.
Invoer: tools/tilerules/input/ (zie README.md).

  python3 tools/tilerules/water_edge.py [invoermap] [uit.lua]
"""
import collections, json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
W_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'input')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', '..', 'mod', 'data', 'gen3_water_edge.lua')
w = json.load(open(os.path.join(W_DIR, 'world.json')))
B = w['behaviors']
WATER_BEH = {0x10, 0x12, 0x15}      # vijver, diep, zee: open water om op te surfen
PURE, SHORE = 0.97, 0.5
cache = {}


def atlas(pair):
    if pair not in cache:
        d = os.path.join(W_DIR, 'atlases', pair)
        m = json.load(open(os.path.join(d, 'meta.json')))
        cols, rows = m['cols'], m['rows']
        def layer(t):
            p = os.path.join(d, 'atlas_%s.rgba' % t)
            return np.frombuffer(open(p, 'rb').read(), np.uint8).reshape(rows * 16, cols * 16, 4) if os.path.exists(p) else None
        slot = {int(x): i for i, x in enumerate(open(os.path.join(d, 'ids.txt')).read().split())}
        cache[pair] = (layer('u'), layer('o'), cols, slot)
    return cache[pair]


def waterness(pair, mid):
    u, o, cols, slot = atlas(pair)
    s = slot.get(mid)
    if s is None or u is None:
        return None
    y0, x0 = (s // cols) * 16, (s % cols) * 16
    t = u[y0:y0 + 16, x0:x0 + 16].astype(float)
    if o is not None:
        top = o[y0:y0 + 16, x0:x0 + 16].astype(float)
        k = top[..., 3:4] / 255.
        t[..., :3] = top[..., :3] * k + t[..., :3] * (1 - k)
    r, g, b = t[..., 0], t[..., 1], t[..., 2]
    return float(((b > r * 1.25) & (b >= g * 0.95)).mean())


use = collections.defaultdict(collections.Counter)
for e in w['maps']:
    if e['pair'].startswith('general__'):
        for v in e['cells']:
            use[e['pair']][v & 0x3FF] += 1
out = {}
for pair in sorted(p for p in B if p.startswith('general__')):
    pure, shore = collections.defaultdict(list), {}
    for ms, beh in B[pair].items():
        mid = int(ms)
        if beh not in WATER_BEH or mid > 0x3FF or use[pair][mid] == 0:
            continue
        wv = waterness(pair, mid)
        if wv is None:
            continue
        if wv >= PURE:
            pure[beh].append((use[pair][mid], mid))
        elif wv >= SHORE:
            shore[mid] = beh
    pick = {beh: max(c)[1] for beh, c in pure.items()}
    rep = {mid: pick[beh] for mid, beh in shore.items() if beh in pick}
    if rep:
        out[pair] = rep
lines = ['-- GENERATED by tools/tilerules/water_edge.py (niet met de hand aanpassen)', 'return {']
for pair, rep in out.items():
    lines.append(" ['%s']={%s}," % (pair, ','.join('[0x%X]=0x%X' % (k, v) for k, v in sorted(rep.items()))))
lines.append('}')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('pairs with shore water:', len(out), 'tiles:', sum(len(r) for r in out.values()))
