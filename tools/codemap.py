#!/usr/bin/env python3
"""Write docs/CODEMAP.md: one line per Lua module (size, purpose from its first comment) and, for big files, the
top-level functions with line numbers, so a session can read a file by line range instead of whole.
   python3 tools/codemap.py"""
import os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GROUPS = [
 ('Scene building (Gen 3 overworld)', r'^Gen3(Scene|SceneCache|SceneOptions|Integration|Tilesets|TileShape|EmeraldShapes|EmeraldInteriors|Outdoor|PinData|Elevation|Boundary|Recap|CamClear)$|^SceneStream$|^TerrainLevels$|^BoundaryScenery$|^RenderDistance$|^RenderRecovery$'),
 ('Terrain, rock, water edges', r'^Gen3(Blocks|Rock|RockSprites|Mass|Hills|Terrain|Cave|Reef|Decks|Stairs|AshPine)$|^VoxelHull$|^Water|^WorldUnderlay$'),
 ('Buildings and interiors', r'^Building|^Gen3(VoxelBuildings|RoofDetails|ObliqueWall|Partition|Furniture|PixelFurniture|PixelFurnitureB|Planter|Market|LeagueGate)$|^RoofEaves$|^InteriorDiorama$|^LandmarkModels$'),
 ('Objects, trees, props', r'^Gen3(Objects|Fence|Lamp|Boat|CableCar|CyclingRoad|Fortree|Canopy|Forest|TreeStamps|Lathe)$|^NativeTreeArt$|^TreePresentation$|^CanopyBillboard$|^SpriteVoxel$|^TowerGraveMist$'),
 ('Fly, camera, tour', r'^Gen3(Fly\w*)$|^FlyMotion$|^Camera|^AtmosphereCamera$|^Tour|^BattleCam$|^DebugWalk$'),
 ('Battle', r'^Gen3Battle\w*$|^Battle\w+$|^Gen3StadiumModels$|^StadiumModels$|^ModelInstances$'),
 ('Renderer, light, sky', r'^Voxel3D$|^VoxelState$|^Mat4$|^Shadow\w*$|^ActorContact$|^DayNight$|^Sky$|^ForestAtmos$|^NativeAtmosphere$|^TiltShift$|^GlassMask$|^DrawUniforms$|^FlatMesh$|^BuildBudget$|^SceneryMask$|^Gen3Sprite\w+$'),
]
def purpose(src):
    out = []
    for ln in src.split('\n')[:8]:
        m = re.match(r'--\s?(.*)', ln)
        if not m:
            if out or ln.strip(): break
            continue
        out.append(m.group(1).strip())
        if len(' '.join(out)) > 90: break
    return ' '.join(out)[:110]
def funcs(src):
    res, lines = [], src.split('\n')
    tops = [(i, m.group(1).split('.')[-1]) for i, ln in enumerate(lines, 1)
            for m in [re.match(r'(?:local )?function ([\w.:]+)\(', ln)] if m]
    for k, (i, n) in enumerate(tops):
        end = tops[k + 1][0] if k + 1 < len(tops) else len(lines)
        res.append('%s@%d' % (n, i))
        if end - i > 300:   # a giant function: list the first call into each other module
            seen, marks = set(), []
            for j in range(i, end):
                m = re.match(r'\s{1,4}(?:local \w+\s*=\s*)?([A-Z]\w+)\.(\w+)\(', lines[j])
                if m and (m.group(1), m.group(2)) not in seen:
                    seen.add((m.group(1), m.group(2))); marks.append('%s.%s@%d' % (m.group(1), m.group(2), j + 1))
            if marks: res.append('[inside %s, first calls: %s]' % (n, ' '.join(marks[:40])))
    return res
def scan(pattern):
    rows = []
    for p in sorted(glob.glob(os.path.join(ROOT, pattern))):
        s = open(p, encoding='utf-8', errors='replace').read()
        rows.append((os.path.basename(p)[:-4], s.count('\n') + 1, purpose(s), funcs(s)))
    return rows
out = ['# Code map (generated by tools/codemap.py; do not edit)', '',
 'Read a module by line range (`offset`/`limit`) using the function index, not whole. Big files are marked with their top-level',
 'functions (`name@line`). Data tables are in `mod/data/` (generated; never read them whole).', '']
def section(title, rows, groups=None, big=500):
    out.append('## ' + title)
    used = set()
    for head, rx in (groups or [(None, '.')]):
        sel = [r for r in rows if r[0] not in used and re.search(rx, r[0])]
        if not sel: continue
        used.update(r[0] for r in sel)
        if head: out.append('### ' + head)
        for n, l, d, f in sel:
            out.append('- `%s` %d: %s' % (n, l, d))
            if l >= big and f: out.append('  - ' + ' '.join(f))
    out.append('')
section('mod/lib (BATTLE_ART_VOXEL_FORK)', scan('mod/lib/*.lua'), GROUPS + [('Other', '.')])
section('stadium2-importer/lib', scan('stadium2-importer/lib/*.lua'), big=700)
section('overworld-wild-spawns/lib/gen3', scan('overworld-wild-spawns/lib/gen3/*.lua') + scan('overworld-wild-spawns/lib/*.lua'), big=700)
open(os.path.join(ROOT, 'docs/CODEMAP.md'), 'w').write('\n'.join(out) + '\n')
print('docs/CODEMAP.md', len('\n'.join(out)), 'bytes')
