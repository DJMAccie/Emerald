#!/usr/bin/env python3
"""scorecard.py: one scorecard row from gate dumps (the training curve).

  scorecard.py --label <name> [--pins /tmp/<lbl>] [--cls /tmp/<lbl>] [--tree <tree_gate output file>]
               [--tree-sunk N --tree-floating N] [--fallbacks N] [--commit <sha>] [--source "..."] [--note "..."]

--pins: a pins_gate.sh dir (pins_*.txt with COUNT/PIN lines) -> maps, pins, exact, diff (G-01).
--cls:  a blocks_gate.sh dir (cls_*.txt with CLS lines)       -> unclassified, faceHigh, massNotFlat (G-02).
--tree: tree_gate.py output ("ALL tree cells N sunk S floating F") or the two numbers by hand (G-03).
--fallbacks: by hand, or summed from the tryp_*.log "fallback N" lines of the dirs given (G-05).
Appends one row to docs/knowledge/scorecard.tsv and rewrites docs/knowledge/scorecard.md (history + per-map table of the
latest run). Missing numbers are written as '-' so a partial run never looks like a zero."""
import argparse, datetime, glob, os, re, subprocess, collections
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
K = os.path.join(R, 'docs', 'knowledge')
COLS = ['date', 'commit', 'label', 'maps', 'pins', 'exact', 'diff', 'unclassified', 'faceHigh', 'massNotFlat', 'treeSunk', 'treeFloating', 'fallbacks', 'source', 'note']

def read_pins(d):
    per = {}
    for f in glob.glob(os.path.join(d, 'pins_*.txt')):
        for line in open(f, encoding='utf-8', errors='replace'):
            m = re.match(r'COUNT (\S+) ok=(\d+) diff=(\d+)', line)
            if m: per[m.group(1)] = {'ok': int(m.group(2)), 'diff': int(m.group(3))}
    return per

def read_cls(d):
    per = {}
    for f in glob.glob(os.path.join(d, 'cls_*.txt')):
        for line in open(f, encoding='utf-8', errors='replace'):
            if not line.startswith('CLS '): continue
            t = line.split(); kv = dict(x.split('=', 1) for x in t[2:] if '=' in x)
            per[t[1]] = {k: int(v) for k, v in kv.items() if re.match(r'-?\d+$', v)}
    return per

def read_fallbacks(dirs):
    n = 0; seen = False
    for d in dirs:
        for f in glob.glob(os.path.join(d, 'tryp_*.log')):
            for m in re.finditer(r'fallback (\d+)', open(f, encoding='utf-8', errors='replace').read()):
                n += int(m.group(1)); seen = True
    return n if seen else None

def read_tree(path):
    m = re.search(r'ALL tree cells \d+ sunk (\d+) floating (\d+)', open(path, encoding='utf-8', errors='replace').read())
    return (int(m.group(1)), int(m.group(2))) if m else (None, None)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--label', required=True); ap.add_argument('--pins'); ap.add_argument('--cls'); ap.add_argument('--tree')
    ap.add_argument('--tree-sunk', type=int); ap.add_argument('--tree-floating', type=int); ap.add_argument('--fallbacks', type=int)
    ap.add_argument('--commit'); ap.add_argument('--source', default=''); ap.add_argument('--note', default='')
    ap.add_argument('--date', default=datetime.date.today().isoformat())
    a = ap.parse_args()
    commit = a.commit or subprocess.run(['git', '-C', R, 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip() or '-'
    pins = read_pins(a.pins) if a.pins else {}
    cls = read_cls(a.cls) if a.cls else {}
    sunk, flt = (a.tree_sunk, a.tree_floating)
    if a.tree: sunk, flt = read_tree(a.tree)
    fb = a.fallbacks if a.fallbacks is not None else read_fallbacks([d for d in (a.pins, a.cls) if d])
    row = {'date': a.date, 'commit': commit, 'label': a.label, 'source': a.source, 'note': a.note,
           'maps': len(set(pins) | set(cls)) or '-',
           'pins': sum(p['ok'] + p['diff'] for p in pins.values()) if pins else '-',
           'exact': sum(p['ok'] for p in pins.values()) if pins else '-',
           'diff': sum(p['diff'] for p in pins.values()) if pins else '-',
           'unclassified': sum(c.get('unclassified', 0) for c in cls.values()) if cls else '-',
           'faceHigh': sum(c.get('faceHigh', 0) for c in cls.values()) if cls else '-',
           'massNotFlat': sum(c.get('massNotFlat', 0) for c in cls.values()) if cls else '-',
           'treeSunk': sunk if sunk is not None else '-', 'treeFloating': flt if flt is not None else '-',
           'fallbacks': fb if fb is not None else '-'}
    tsv = os.path.join(K, 'scorecard.tsv')
    new = not os.path.exists(tsv)
    with open(tsv, 'a', encoding='utf-8') as f:
        if new: f.write('\t'.join(COLS) + '\n')
        f.write('\t'.join(str(row[c]).replace('\t', ' ') for c in COLS) + '\n')
    rows = [dict(zip(COLS, l.rstrip('\n').split('\t'))) for l in open(tsv, encoding='utf-8').readlines()[1:]]
    out = ['# Scorecard', '',
           'Generated by `tools/knowledge/scorecard.py`; do not edit by hand. One row per gate run on the installed world, newest last.',
           'Columns: pins / exact / diff = G-01 (R-01, R-10); unclassified / faceHigh / massNotFlat = G-02 (R-02, R-03, R-05);',
           'treeSunk / treeFloating = G-03 (R-15); fallbacks = G-05 (R-23, R-27). Targets: diff 0, unclassified 0, massNotFlat 0,',
           'treeSunk 0, fallbacks 0, faceHigh falling with every remaining cell explained. `-` = that gate was not in the run.', '',
           '## History', '',
           '| ' + ' | '.join(COLS[:13]) + ' |', '|' + '---|' * 13]
    for r in rows: out.append('| ' + ' | '.join(r[c] for c in COLS[:13]) + ' |')
    out += ['', '## Sources and notes', '']
    for r in rows: out.append('- %s %s: %s %s' % (r['date'], r['label'], r['source'], ('(%s)' % r['note']) if r['note'] else ''))
    if pins or cls:
        out += ['', '## Per map, latest run (%s, %s)' % (a.label, commit), '',
                '| map | pins | exact | diff | unclassified | faceHigh | massNotFlat | rock cells |', '|---|---:|---:|---:|---:|---:|---:|---:|']
        for m in sorted(set(pins) | set(cls)):
            p = pins.get(m, {}); c = cls.get(m, {})
            out.append('| %s | %s | %s | %s | %s | %s | %s | %s |' % (m, (p.get('ok', 0) + p.get('diff', 0)) if p else '-', p.get('ok', '-'), p.get('diff', '-'),
                       c.get('unclassified', '-'), c.get('faceHigh', '-'), c.get('massNotFlat', '-'), c.get('rock', '-')))
    open(os.path.join(K, 'scorecard.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('\t'.join('%s=%s' % (c, row[c]) for c in COLS[:13]))

if __name__ == '__main__': main()
