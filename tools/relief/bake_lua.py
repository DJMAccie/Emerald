#!/usr/bin/env python3
"""Bake terraces.py's relief into a Lua data file the mod reads at run time.

    python3 bake_lua.py OUT.lua Route111 Route114 [...]

Output (lib/Gen3ReliefData.lua) is one table per map, in the given order:

  EM_ROUTE111 = { w = 40, h = 140, cells = { [y*w + x + 1] = "G|D|WX,WY" } }

  G   25 integers (px, 5 x 5 lattice, rows north to south): the counted relief
      of the cell, level 0 = the map's biggest ground (3DS: heights in px,
      16 px a level);
  D   25 integers (px x 4): our soft shoulders and rolling tops as a change
      to G (render.soften minus the counted heights);
  WX,WY  the cell whose drawing is the face tile this cell's walls wear
      (render.wall_tile's nearest face within 4 cells), or "-".

Only cells that matter are written: every rock, top and unknown cell, and the
ground within one cell of them (the consumer reads those for the seam).
Deterministic: maps in the given order, cells by index.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np  # noqa: E402

import emdata as E  # noqa: E402
import importlib.util  # noqa: E402

import terraces as T  # noqa: E402

# (tools/analysis has a render.py too and emdata puts it first on the path)
_spec = importlib.util.spec_from_file_location("relief_render", os.path.join(HERE, "render.py"))
R = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(R)

FACE_IDS = (0x07c, 0x0a9, 0x079, 0x091)
N = 4


def nearest_face(J, x, y):
    for r in range(0, 5):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                if max(abs(dx), abs(dy)) != r:
                    continue
                xx, yy = x + dx, y + dy
                if 0 <= xx < J["w"] and 0 <= yy < J["h"] and J["read_as"][yy][xx] in FACE_IDS:
                    return xx, yy
    return None


def bake(name):
    layout = E.Layout(name)
    sol = T.solve(layout)
    J = T.to_json(layout, sol)
    grids = {}
    for y in range(J["h"]):
        for x in range(J["w"]):
            grids[(x, y)] = np.array(J["grids"][y][x], float).reshape(N + 1, N + 1)
    soft = R.soften(J, grids)
    W, H = J["w"], J["h"]
    kind = J["kind"]
    core = {(x, y) for y in range(H) for x in range(W) if kind[y][x] in "TR?"}
    keep = set()
    for (x, y) in core:
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                if 0 <= x + dx < W and 0 <= y + dy < H:
                    keep.add((x + dx, y + dy))
    cells = []
    worst = 0.0
    for (x, y) in sorted(keep, key=lambda p: p[1] * W + p[0]):
        g = grids[(x, y)]
        d = soft[(x, y)] - g
        gi = np.rint(g).astype(int)
        worst = max(worst, float(np.abs(g - gi).max()))
        di = np.rint(d * 4).astype(int)
        f = nearest_face(J, x, y)
        cells.append((y * W + x + 1,
                      "%s|%s|%s" % (" ".join(map(str, gi.flatten())),
                                    " ".join(map(str, di.flatten())),
                                    "%d,%d" % f if f else "-")))
    return J["em"], W, H, cells, worst


def main():
    out = sys.argv[1]
    maps = sys.argv[2:]
    lines = ["-- Generated by tools/relief/bake_lua.py from the counted relief of Emerald 3DS'",
             "-- terrace method (MIT, see tools/relief/NOTICE.md). Do not edit by hand.",
             "return {"]
    for name in maps:
        em, W, H, cells, worst = bake(name)
        print("%-10s %s  %d cells baked, worst rounding %.2f px" % (name, em, len(cells), worst))
        lines.append(" %s={w=%d,h=%d,cells={" % (em, W, H))
        for idx, s in cells:
            lines.append("  [%d]=%s," % (idx, json.dumps(s)))
        lines.append(" }},")
    lines.append("}")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
