#!/usr/bin/env python3
"""Coverage ledger: how much of Emerald 3D is done, per map and area, generated, never hand-typed.

Inputs (all in docs/ledger/):
  maps.json     every map: id, kind, w, h. Refresh with --refresh-maps (reads world.json from the modwork folder).
  status.json   review state per map and area; kind defaults for everything not listed.
  faults.json   the one list of known faults (id, map, area, tier, class, cell, text, status).
  audits.json   global audit numbers with their source and date.
Output: docs/LEDGER.md (--write). --check exits 1 if the file is stale or the data disagree.

States (the weights are Emerald 3DS's scale, so the percentages compare):
  none 0  wip .5  modelled .6 (built, unreviewed)  faults .75 (known faults listed)  done 1 (reviewed in game, none known)
Rules enforced here:
  - an area in 'modelled' or 'wip' with an open fault is shown as 'faults';
  - 'done' with an open fault is an error;
  - 'done' may only be set by the user (record it in status.json under "signed_off": {"map": "date"}).
Tiers (docs/DONE.md): tier 1 faults block a release, tier 2 are polish.
"""
import json, sys, os, argparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LED = os.path.join(ROOT, 'docs', 'ledger')
OUT = os.path.join(ROOT, 'docs', 'LEDGER.md')
WORLD = os.path.expanduser('~/Documents/gen1recomp-modwork/world.json')

EMOJI = {'none': '⬜', 'wip': '🟦', 'modelled': '🟨', 'faults': '🟧', 'done': '✅'}
WEIGHT = {'none': 0.0, 'wip': 0.5, 'modelled': 0.6, 'faults': 0.75, 'done': 1.0}
KIND_OF_TYPE = {1: 'town_city', 2: 'town_city', 3: 'route', 6: 'water_route', 4: 'cave', 8: 'interior', 9: 'secret_base', 5: 'underwater'}
KIND_TITLE = {'town_city': 'Towns and cities', 'route': 'Routes', 'water_route': 'Water routes', 'cave': 'Caves and dungeons',
              'interior': 'Interiors', 'secret_base': 'Secret bases', 'underwater': 'Underwater'}
OUTDOOR = ('town_city', 'route', 'water_route')
AREAS = {k: (['Terrain', 'Buildings', 'Props'] if k in OUTDOOR else ['Shell', 'Furniture']) for k in KIND_TITLE}


def load(name):
    with open(os.path.join(LED, name)) as f:
        return json.load(f)


def refresh_maps():
    with open(WORLD) as f:
        world = json.load(f)['maps']
    rows = [{'id': m['id'], 'kind': KIND_OF_TYPE[m['type']], 'w': m['w'], 'h': m['h']} for m in world]
    with open(os.path.join(LED, 'maps.json'), 'w') as f:
        json.dump(rows, f, indent=0)
        f.write('\n')
    print('maps.json:', len(rows), 'maps')


def effective(maps, status, faults):
    """-> {map_id: {area: state}} after the fault rules, plus a list of errors."""
    errors = []
    open_by = {}
    for fl in faults:
        if fl.get('status', 'open') == 'open':
            open_by.setdefault((fl['map'], fl['area']), []).append(fl)
    ids = {m['id'] for m in maps}
    for fl in faults:
        if fl['map'] not in ids:
            errors.append('fault %s: unknown map %s' % (fl.get('id'), fl['map']))
    result = {}
    for m in maps:
        d = status['defaults'][m['kind']]
        over = status['maps'].get(m['id'], {})
        row = {}
        for a in AREAS[m['kind']]:
            s = over.get(a, d.get(a, 'none'))
            has_open = (m['id'], a) in open_by
            if s == 'done' and has_open:
                errors.append('%s %s is done but has open faults' % (m['id'], a))
            if s == 'done' and m['id'] not in status.get('signed_off', {}):
                errors.append('%s %s is done but not signed off by the user' % (m['id'], a))
            if s in ('modelled', 'wip') and has_open:
                s = 'faults'
            row[a] = s
        result[m['id']] = row
    return result, open_by, errors


def pct(cells):
    return 100.0 * sum(WEIGHT[c] for c in cells) / len(cells) if cells else 0.0


def render(maps, status, faults, audits):
    eff, open_by, errors = effective(maps, status, faults)
    kinds = {}
    for m in maps:
        kinds.setdefault(m['kind'], []).append(m)
    allcells = [s for r in eff.values() for s in r.values()]
    out = []
    w = out.append
    w('# Emerald 3D coverage ledger')
    w('')
    w('Generated by `tools/ledger.py --write` from `docs/ledger/*.json`. Do not edit by hand. What counts as shippable: [DONE.md](DONE.md).')
    w('')
    w('**Progress %.1f%%  |  Complete %.1f%%**  (%d map-areas in %d maps; %d open faults, %d of them tier 1)' % (
        pct(allcells), 100.0 * allcells.count('done') / len(allcells), len(allcells), len(maps),
        sum(len(v) for v in open_by.values()), sum(1 for v in open_by.values() for f in v if f.get('tier') == 1)))
    w('')
    w('Scale: ⬜ not started · 🟦 in progress · 🟨 built, unreviewed · 🟧 known faults listed · ✅ reviewed in game by the user, none known. ' +
      'Weights 0 / .5 / .6 / .75 / 1 (Emerald 3DS\'s, so the percentages compare). Seed: ' + status.get('seed_note', '') )
    w('')
    w('## By group')
    w('')
    w('| Group | Maps | Progress | ⬜ | 🟦 | 🟨 | 🟧 | ✅ |')
    w('|---|---:|---:|---:|---:|---:|---:|---:|')
    for k in KIND_TITLE:
        ms = kinds.get(k, [])
        cells = [s for m in ms for s in eff[m['id']].values()]
        if not cells:
            continue
        w('| %s | %d | %.1f%% | %s |' % (KIND_TITLE[k], len(ms), pct(cells),
                                           ' | '.join(str(cells.count(s)) for s in ('none', 'wip', 'modelled', 'faults', 'done'))))
    w('')
    w('## Audits (numbers, with source)')
    w('')
    w('| Audit | Value | Target | As of | Source |')
    w('|---|---|---|---|---|')
    for it in audits['items']:
        w('| %s | %s | %s | %s | %s |' % (it['name'], it['value'], it['target'], it['asof'], it['source']))
    w('')
    w('## Open faults')
    w('')
    openf = [f for f in faults if f.get('status', 'open') == 'open']
    if not openf:
        w('None.')
    else:
        w('| Id | Tier | Map | Area | Class | Cell | Fault |')
        w('|---|---:|---|---|---|---|---|')
        for f in sorted(openf, key=lambda f: (f.get('tier', 2), f['map'], f['id'])):
            w('| %s | %s | %s | %s | %s | %s | %s |' % (f['id'], f.get('tier', 2), f['map'], f['area'], f.get('class', ''),
                                                       f.get('cell', ''), f['text']))
    w('')
    w('## Outdoor maps')
    w('')
    w('| Map | Terrain | Buildings | Props | Open faults |')
    w('|---|:-:|:-:|:-:|---:|')
    for k in OUTDOOR:
        for m in kinds.get(k, []):
            r = eff[m['id']]
            n = sum(len(open_by.get((m['id'], a), [])) for a in AREAS[k])
            w('| %s | %s | %s | %s | %d |' % (m['id'], EMOJI[r['Terrain']], EMOJI[r['Buildings']], EMOJI[r['Props']], n))
    w('')
    w('## Indoor and other maps')
    w('')
    w('Listed only when they differ from their group default or carry an open fault; the rest sit at the group default shown in the table above.')
    w('')
    w('| Map | Group | Shell | Furniture | Open faults |')
    w('|---|---|:-:|:-:|---:|')
    shown = 0
    for k in KIND_TITLE:
        if k in OUTDOOR:
            continue
        d = status['defaults'][k]
        for m in kinds.get(k, []):
            r = eff[m['id']]
            n = sum(len(open_by.get((m['id'], a), [])) for a in AREAS[k])
            if n or any(r[a] != d.get(a, 'none') for a in r):
                w('| %s | %s | %s | %s | %d |' % (m['id'], KIND_TITLE[k], EMOJI[r['Shell']], EMOJI[r['Furniture']], n))
                shown += 1
    if not shown:
        w('| (none) | | | | |')
    w('')
    return '\n'.join(out), errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--refresh-maps', action='store_true')
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if a.refresh_maps:
        refresh_maps()
    maps, status, faults, audits = load('maps.json'), load('status.json'), load('faults.json'), load('audits.json')
    text, errors = render(maps, status, faults, audits)
    for e in errors:
        print('ERROR', e, file=sys.stderr)
    if a.write:
        with open(OUT, 'w') as f:
            f.write(text)
        print('wrote', OUT)
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            print('docs/LEDGER.md is stale: run tools/ledger.py --write', file=sys.stderr)
            return 1
    if not (a.write or a.check or a.refresh_maps):
        print(text)
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
