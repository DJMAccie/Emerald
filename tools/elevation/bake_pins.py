#!/usr/bin/env python3
"""bake_pins.py [out.lua]: docs/elevation/pins/<MAP>.txt (the user's hand-drawn heights, `x y h` per mark, courses of 16 px)
-> lib/Gen3PinData.lua. `^ up` rows (arrows) go to ARROWS. _proposed.txt files are skipped (phase 2 output, not truth).
The data file is generated: never hand-edit it (same pattern as Gen3ReliefData)."""
import os, sys, glob
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..', '..')
PINS = os.path.join(ROOT, 'docs', 'elevation', 'pins')
out = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Documents/battle-art-notquiteog/lib/Gen3PinData.lua')
maps, arrows = {}, {}
for f in sorted(glob.glob(os.path.join(PINS, 'EM_*.txt'))):
    m = os.path.basename(f)[:-4]
    if m.endswith('_proposed'): continue
    for line in open(f):
        t = line.split('#')[0].split()
        if len(t) < 3: continue
        x, y = int(t[0]), int(t[1])
        if t[2].replace('.', '', 1).lstrip('-').isdigit(): maps.setdefault(m, []).append((x, y, float(t[2]) if '.' in t[2] else int(t[2])) + ((1,) if len(t) > 3 and t[3] == 'top' else ()))
        elif t[2] == '^': arrows.setdefault(m, []).append((x, y))
L = ['-- GENERATED by tools/elevation/bake_pins.py from docs/elevation/pins/*.txt (the user\'s hand-drawn heights). Do not edit.',
     '-- MAPS[map]={{x,y,courses},...}: one mark per flat area / rock top; a 4th value 1 = `top` (a rock or ledge top: this cell only, no plateau flood), courses of 16 px relative to the map\'s own ground 0, water 0.',
     'local M={MAPS={},ARROWS={}}']
for m, rows in sorted(maps.items()):
    L.append('M.MAPS.%s={%s}' % (m, ','.join('{' + ','.join(('%g' % v) if isinstance(v, float) else str(v) for v in r) + '}' for r in rows)))
for m, rows in sorted(arrows.items()):
    L.append('M.ARROWS.%s={%s}' % (m, ','.join('{%d,%d}' % r for r in rows)))
L.append('return M')
open(out, 'w').write('\n'.join(L) + '\n'); print(out, len(maps), 'maps', sum(map(len, maps.values())), 'pins')
