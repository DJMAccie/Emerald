#!/usr/bin/env python3
"""Generate lib/Gen3WaterEdge.lua: for each General tileset pair, which water tiles carry shore pixels
(sand/foam baked in) and which plain open-water tile of the SAME behaviour replaces them when the
boundary code repeats water beyond a map's edge (Gen3Boundary.resolve).
  cd tools/buildings && python3 ../props/gen_water_edge.py > ~/Documents/battle-art-notquiteog/lib/Gen3WaterEdge.lua
Offline: uses the tile atlases (tools/analysis/layers.py) and world.json only."""
import os, sys, json, collections
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'buildings'))
import bldmodel  # noqa: F401
import layers
w = json.load(open(os.path.expanduser('~/Documents/gen1recomp-modwork/world.json')))
B = w['behaviors']
WATER_BEH = {0x10, 0x12, 0x15}      # pond, deep, ocean: open water you can surf on
PURE, SHORE = 0.97, 0.5
cache = {}


def waterness(pair, mid):
    if pair not in cache:
        cache[pair] = layers.load(pair)
    L = cache[pair]
    u = layers.tile(L, 'u', mid)
    if u is None:
        return None
    u = u.astype(float)
    if 'o' in L:
        o = layers.tile(L, 'o', mid)
        if o is not None:
            k = o[..., 3:4] / 255.
            u[..., :3] = o[..., :3] * k + u[..., :3] * (1 - k)
    r, g, b = u[..., 0], u[..., 1], u[..., 2]
    return float(((b > r * 1.25) & (b >= g * 0.95)).mean())


use = collections.defaultdict(collections.Counter)
for e in w['maps']:
    if e['pair'].startswith('general__'):
        for v in e['cells']:
            use[e['pair']][v & 0x3FF] += 1
out = {}
for pair in sorted(p for p in B if p.startswith('general__')):
    pure, shore = collections.defaultdict(list), {}
    for ms, beh in B[pair].items():
        mid = int(ms)
        if beh not in WATER_BEH or mid > 0x3FF or use[pair][mid] == 0:
            continue
        try:
            wv = waterness(pair, mid)
        except Exception:
            continue
        if wv is None:
            continue
        if wv >= PURE:
            pure[beh].append((use[pair][mid], mid))
        elif wv >= SHORE:
            shore[mid] = beh
    pick = {beh: max(c)[1] for beh, c in pure.items()}
    rep = {mid: pick[beh] for mid, beh in shore.items() if beh in pick}
    if rep:
        out[pair] = rep
print('-- GENERATED by tools/props/gen_water_edge.py (do not edit). Water tiles with shore pixels baked in ->')
print('-- the plain open-water tile of the same behaviour in the same tileset pair. Gen3Boundary repeats water')
print('-- beyond a map edge; repeating a shore tile repeated the shoreline.')
print('local M={}')
print('M.REPLACE={')
for pair, rep in out.items():
    print(" ['%s']={%s}," % (pair, ','.join('[0x%X]=0x%X' % (k, v) for k, v in sorted(rep.items()))))
print('}')
print('-- the replacement for `mid` in `pair`, or `mid` itself when it is already plain water / unknown')
print('function M.plain(pair,mid)')
print(' local t=M.REPLACE[pair]')
print(' return t and t[mid] or mid')
print('end')
print('return M')
